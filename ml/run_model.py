"""Train the final models, save them, and score them once on the test week.

Run:  uv run python -m ml.run_model

Trains on the whole training period (targets before SPLIT) with the tuned
settings in ml.model and ml.probability, saves models/, and writes:
- results/model.{csv,md}: MAE model on the test week (main result)
- results/probability.{csv,md}, results/calibration.png: the classifiers on
  the test week
- results/*_november.{csv,md}: the same for origins from TEST_END to the end of
  the data, reported separately to see how the models hold up over time
"""

import logging
import sys
from pathlib import Path

import lightgbm as lgb
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from ml.baselines import Unchanged, derive_docks  # noqa: E402
from ml.config import SPLIT, TEST_END  # noqa: E402
from ml.evaluate import mae_table, to_wide  # noqa: E402
from ml.features import add_features, nearest_neighbours  # noqa: E402
from ml.grid import OSLO, load_stations, load_status, to_grid  # noqa: E402
from ml.model import FINAL_ROUNDS, PARAMS, predict, save, train  # noqa: E402
from ml.pairs import late_period, make_pairs, split  # noqa: E402
from ml.probability import (  # noqa: E402
    CLS_FINAL_ROUNDS,
    CLS_PARAMS,
    FEW,
    TARGETS,
    CountTable,
    UnchangedProbability,
    brier_table,
    calibration,
    outcome,
    predict_proba,
    train_classifier,
)
from ml.run_baselines import markdown_table  # noqa: E402

RESULTS_DIR = Path("results")
FMT = "%Y-%m-%d %H:%M %Z"
log = logging.getLogger("model")


def score(pairs: pd.DataFrame, booster: lgb.Booster) -> pd.DataFrame:
    """Long MAE table for the model and `unchanged`, bikes and derived docks."""
    bikes = {
        "unchanged": Unchanged().predict(pairs),
        "lightgbm": predict(booster, pairs),
    }
    docks = {name: derive_docks(pairs, b) for name, b in bikes.items()}
    return pd.concat(
        [mae_table(pairs, bikes, "bikes"), mae_table(pairs, docks, "docks")],
        ignore_index=True,
    )


def probabilities(pairs, classifiers, tables) -> dict[str, dict[str, object]]:
    """Predicted probabilities per target and model."""
    return {
        target: {
            "unchanged": UnchangedProbability(target).predict(pairs),
            "count_table": tables[target].predict(pairs),
            "lightgbm": predict_proba(classifiers[target], pairs),
        }
        for target in TARGETS
    }


def gain_table(table: pd.DataFrame, value: str, baseline: str) -> pd.DataFrame:
    """Model vs baseline and the relative gain (positive = model better)."""
    wide = table.pivot_table(
        index=["target", "subset", "horizon"], columns="model", values=value
    ).reset_index()
    wide["gain"] = (1 - wide["lightgbm"] / wide[baseline]).map(lambda g: f"{g:+.1%}")
    wide["horizon"] = wide["horizon"].map(lambda h: f"{h} min")
    return wide[["target", "subset", "horizon", baseline, "lightgbm", "gain"]]


def counts(table: pd.DataFrame, target: str) -> pd.DataFrame:
    n = table[(table["target"] == target) & (table["model"] == "unchanged")]
    n = n.pivot_table(index="subset", columns="horizon", values="n").astype(int)
    n.columns = [f"{h} min" for h in n.columns]
    return n.reset_index()


def header(title: str, period: str, facts: dict, trees: str) -> str:
    return f"""# {title}

Generated by `uv run python -m ml.run_model`.

- Model: LightGBM, {trees}, trained on pairs with target before
  {SPLIT.strftime(FMT)} ({facts["train_pairs"]} pairs)
- {period}
- Pairs: {facts["pairs"]}, {facts["stations"]} stations
"""


def mae_report(title: str, period: str, table: pd.DataFrame, facts: dict) -> str:
    wide = to_wide(table)
    return f"""{header(title, period, facts, f"{FINAL_ROUNDS} trees")}
Mean absolute error (MAE) in number of bikes or docks; lower is better. Docks
are derived from predicted bikes. Gain = 1 - lightgbm / unchanged.

## Bikes

{markdown_table(wide[wide["target"] == "bikes"].drop(columns="target"))}

## Docks (derived from predicted bikes)

{markdown_table(wide[wide["target"] == "docks"].drop(columns="target"))}

## Gain over `unchanged`

{markdown_table(gain_table(table, "mae", "unchanged"))}

## Number of pairs per subset

{markdown_table(counts(table, "bikes"))}
"""


def probability_report(title: str, period: str, table: pd.DataFrame, facts) -> str:
    trees = ", ".join(f"{n} trees ({t})" for t, n in CLS_FINAL_ROUNDS.items())
    sections = []
    for target in TARGETS:
        t = table[table["target"] == target]
        brier = t.pivot_table(
            index=["subset", "model"], columns="horizon", values="brier"
        )
        brier.columns = [f"{h} min" for h in brier.columns]
        log_loss = t.pivot_table(
            index=["subset", "model"], columns="horizon", values="log_loss"
        )
        log_loss.columns = [f"{h} min" for h in log_loss.columns]
        sections.append(f"""## P(at least one {target})

Brier score:

{markdown_table(brier.reset_index())}

Log loss:

{markdown_table(log_loss.reset_index())}

Gain over the count table (Brier):

{markdown_table(gain_table(t, "brier", "count_table").drop(columns="target"))}
""")
    return f"""{header(title, period, facts, trees)}
Brier score = mean squared difference between the predicted probability and
the outcome (0 or 1); lower is better. `unchanged` is 100 % if there is one
now, else 0 %. `count_table` is the share with at least one at the target in
training, by number now and horizon. `few_now` = at most {FEW} available now.
See `calibration.png` for the test week.

{"".join(sections)}
## Number of pairs per subset (bikes)

{markdown_table(counts(table, "bike"))}
"""


def calibration_plot(pairs: pd.DataFrame, probs: dict, path: Path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5))
    for ax, target in zip(axes, TARGETS, strict=True):
        truth = outcome(pairs, target)
        for name in ["count_table", "lightgbm"]:
            c = calibration(probs[target][name], truth)
            ax.plot(c["predicted"], c["observed"], marker="o", label=name)
        ax.plot([0, 1], [0, 1], color="grey", ls="--", lw=0.8, label="perfect")
        ax.set(
            xlabel="predicted probability",
            ylabel="observed share",
            title=f"P(at least one {target}), test week",
        )
        ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=100)
    plt.close(fig)


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    grid = to_grid(load_status())
    stations_df = load_stations()
    pairs = make_pairs(grid, stations_df)
    train_pairs, test_pairs = split(pairs)
    late_pairs = late_period(pairs)
    stations = sorted(pairs["station_id"].unique().tolist())
    neighbours = nearest_neighbours(stations_df)

    def features(p):
        return add_features(p, grid, stations=stations, neighbours=neighbours)

    train_f = features(train_pairs)
    booster, _ = train(train_f, None, PARAMS, rounds=FINAL_ROUNDS)
    classifiers = {
        target: train_classifier(train_f, None, target, CLS_PARAMS, rounds=n)[0]
        for target, n in CLS_FINAL_ROUNDS.items()
    }
    tables = {target: CountTable(target).fit(train_f) for target in TARGETS}
    info = {
        "trained_on": f"targets before {SPLIT.isoformat()}",
        "trees": FINAL_ROUNDS,
        "classifier_trees": CLS_FINAL_ROUNDS,
        "train_pairs": len(train_f),
        "lightgbm_version": lgb.__version__,
        "neighbours": neighbours,
    }
    save(booster, stations, info, classifiers=classifiers)
    log.info("Models saved to models/")

    RESULTS_DIR.mkdir(exist_ok=True)
    data_end = grid["slot"].max().tz_convert(OSLO)
    periods = {
        "": (
            test_pairs,
            "test week",
            f"Test: origins from {SPLIT.strftime(FMT)} to {TEST_END.strftime(FMT)}",
        ),
        "_november": (
            late_pairs,
            "after the test week (November)",
            f"Period: origins from {TEST_END.strftime(FMT)} to {data_end.strftime(FMT)}"
            " (never used for any choice)",
        ),
    }
    for suffix, (p, label, period) in periods.items():
        f = features(p)
        facts = {
            "train_pairs": len(train_f),
            "pairs": len(f),
            "stations": f["station_id"].nunique(),
        }
        mae = score(f, booster)
        mae.to_csv(RESULTS_DIR / f"model{suffix}.csv", index=False, float_format="%.4f")
        text = mae_report(f"MAE model, {label}", period, mae, facts)
        (RESULTS_DIR / f"model{suffix}.md").write_text(text, encoding="utf-8")

        probs = probabilities(f, classifiers, tables)
        prob = pd.concat(
            [brier_table(f, probs[t], t) for t in TARGETS], ignore_index=True
        )
        prob.to_csv(
            RESULTS_DIR / f"probability{suffix}.csv", index=False, float_format="%.4f"
        )
        text = probability_report(f"Probability models, {label}", period, prob, facts)
        (RESULTS_DIR / f"probability{suffix}.md").write_text(text, encoding="utf-8")
        if not suffix:
            calibration_plot(f, probs, RESULTS_DIR / "calibration.png")
        log.info("Results for the %s written to results/", label)
    return 0


if __name__ == "__main__":
    sys.exit(main())
