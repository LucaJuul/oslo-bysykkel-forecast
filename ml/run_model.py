"""Train the final LightGBM model, save it, and score it once on the test week.

Run:  uv run python -m ml.run_model

Trains on the whole training period (targets before SPLIT) with the tuned
settings in ml.model, saves models/, and writes:
- results/model.csv, results/model.md: the test week, the main result
- results/model_november.csv, results/model_november.md: origins from TEST_END
  to the end of the data, reported separately to see how the model holds up
"""

import logging
import sys
from pathlib import Path

import lightgbm as lgb
import pandas as pd

from ml.baselines import Unchanged, derive_docks
from ml.config import SPLIT, TEST_END
from ml.evaluate import mae_table, to_wide
from ml.features import add_features
from ml.grid import OSLO, load_stations, load_status, to_grid
from ml.model import FINAL_ROUNDS, PARAMS, predict, save, train
from ml.pairs import late_period, make_pairs, split
from ml.run_baselines import markdown_table

RESULTS_DIR = Path("results")
FMT = "%Y-%m-%d %H:%M %Z"
log = logging.getLogger("model")


def score(pairs: pd.DataFrame, booster: lgb.Booster) -> pd.DataFrame:
    """Long MAE table for the model and `unchanged`, bikes and derived docks."""
    bikes = {
        "unchanged": Unchanged().predict(pairs),
        "lightgbm": predict(booster, pairs),
    }
    docks = {name: derive_docks(pairs, b) for name, b in bikes.items()}
    return pd.concat(
        [mae_table(pairs, bikes, "bikes"), mae_table(pairs, docks, "docks")],
        ignore_index=True,
    )


def gain_table(table: pd.DataFrame) -> pd.DataFrame:
    """Wide table with model, unchanged and the relative gain, bikes and docks."""
    wide = table.pivot_table(
        index=["target", "subset", "horizon"], columns="model", values="mae"
    ).reset_index()
    wide["gain"] = 1 - wide["lightgbm"] / wide["unchanged"]
    wide["gain"] = wide["gain"].map(lambda g: f"{g:+.1%}")
    wide["horizon"] = wide["horizon"].map(lambda h: f"{h} min")
    return wide[["target", "subset", "horizon", "unchanged", "lightgbm", "gain"]]


def report(title: str, period: str, table: pd.DataFrame, facts: dict) -> str:
    wide = to_wide(table)
    gains = gain_table(table)
    n = table[(table["target"] == "bikes") & (table["model"] == "unchanged")]
    n = n.pivot_table(index="subset", columns="horizon", values="n").astype(int)
    n.columns = [f"{h} min" for h in n.columns]
    return f"""# {title}

Generated by `uv run python -m ml.run_model`. Mean absolute error (MAE) in
number of bikes or docks; lower is better. Docks are derived from predicted
bikes. Gain = 1 - lightgbm / unchanged (positive means the model is better).

- Model: LightGBM, {FINAL_ROUNDS} trees, trained on pairs with target before
  {SPLIT.strftime(FMT)} ({facts["train_pairs"]} pairs)
- {period}
- Pairs: {facts["pairs"]}, {facts["stations"]} stations

## Bikes

{markdown_table(wide[wide["target"] == "bikes"].drop(columns="target"))}

## Docks (derived from predicted bikes)

{markdown_table(wide[wide["target"] == "docks"].drop(columns="target"))}

## Gain over `unchanged`

{markdown_table(gains)}

## Number of pairs per subset

{markdown_table(n.reset_index())}
"""


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    grid = to_grid(load_status())
    stations_df = load_stations()
    pairs = make_pairs(grid, stations_df)
    train_pairs, test_pairs = split(pairs)
    late_pairs = late_period(pairs)
    stations = sorted(pairs["station_id"].unique().tolist())

    def features(p):
        return add_features(p, grid, stations=stations)

    train_f = features(train_pairs)
    booster, _ = train(train_f, None, PARAMS, rounds=FINAL_ROUNDS)
    info = {
        "trained_on": f"targets before {SPLIT.isoformat()}",
        "trees": FINAL_ROUNDS,
        "train_pairs": len(train_f),
        "lightgbm_version": lgb.__version__,
    }
    save(booster, stations, info)
    log.info("Model saved to models/")

    RESULTS_DIR.mkdir(exist_ok=True)
    data_end = grid["slot"].max().tz_convert(OSLO)
    periods = {
        "model": (
            test_pairs,
            "Results on the test week (Phase 4)",
            f"Test: origins from {SPLIT.strftime(FMT)} to {TEST_END.strftime(FMT)}",
        ),
        "model_november": (
            late_pairs,
            "Results after the test week (November)",
            f"Period: origins from {TEST_END.strftime(FMT)} to {data_end.strftime(FMT)}"
            " (never used for any choice)",
        ),
    }
    for name, (p, title, period) in periods.items():
        f = features(p)
        table = score(f, booster)
        table.to_csv(RESULTS_DIR / f"{name}.csv", index=False, float_format="%.4f")
        facts = {
            "train_pairs": len(train_f),
            "pairs": len(f),
            "stations": f["station_id"].nunique(),
        }
        text = report(title, period, table, facts)
        (RESULTS_DIR / f"{name}.md").write_text(text, encoding="utf-8")
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
