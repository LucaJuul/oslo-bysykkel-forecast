"""Evaluate the baseline models on the fixed test week and save the results.

Run:  uv run python -m ml.run_baselines

Reads data/*.parquet (make a fresh export first), prints data checks and
writes results/baselines.csv (long format, for Phase 4) and
results/baselines.md (readable tables).
"""

import logging
import sys
from pathlib import Path

import pandas as pd

from ml.baselines import MeanChange, SameTimeLastWeek, Unchanged, derive_docks
from ml.config import SPLIT, TEST_END
from ml.evaluate import mae_table, to_wide
from ml.grid import OSLO, load_stations, load_status, to_grid
from ml.pairs import capacity_check, exclusion_summary, make_pairs, split

RESULTS_DIR = Path("results")
log = logging.getLogger("baselines")


def run(status: pd.DataFrame, stations: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    """Return the long MAE table and a dict of facts for the report."""
    grid = to_grid(status)
    last_slot = grid["slot"].max()
    if last_slot < TEST_END + pd.Timedelta("1h"):
        log.warning("Data ends %s, before the test week is complete.", last_slot)

    pairs = make_pairs(grid, stations)
    train, test = split(pairs)

    models = [Unchanged(), SameTimeLastWeek(grid), MeanChange()]
    bikes, docks = {}, {}
    for model in models:
        model.fit(train)
        bikes[model.name] = model.predict(test)
        docks[model.name] = derive_docks(test, bikes[model.name])

    table = pd.concat(
        [mae_table(test, bikes, "bikes"), mae_table(test, docks, "docks")],
        ignore_index=True,
    )
    facts = {
        "data_end": last_slot,
        "train_pairs": len(train),
        "test_pairs": len(test),
        "test_stations": test["station_id"].nunique(),
        "excluded": exclusion_summary(pairs[pairs["slot"] >= SPLIT]),
        "frozen_stations": sorted(
            pairs.loc[(pairs["slot"] >= SPLIT) & pairs["frozen"], "station_id"]
            .unique()
            .tolist()
        ),
        "capacity": capacity_check(grid, stations),
        "last_week_fallback": models[1].fallback_share,
    }
    return table, facts


def markdown_table(df: pd.DataFrame) -> str:
    def cell(v):
        return f"{v:.3f}" if isinstance(v, float) else str(v)

    lines = [
        "| " + " | ".join(df.columns) + " |",
        "|" + "---|" * len(df.columns),
    ]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.values]
    return "\n".join(lines)


def report(table: pd.DataFrame, facts: dict) -> str:
    wide = to_wide(table)
    counts = table[(table["target"] == "bikes") & (table["model"] == "unchanged")]
    counts = counts.pivot_table(index="subset", columns="horizon", values="n")
    counts = counts.astype(int)
    counts.columns = [f"{h} min" for h in counts.columns]
    cap = facts["capacity"]
    excluded = facts["excluded"]
    fmt = "%Y-%m-%d %H:%M %Z"
    return f"""# Baseline results (Phase 3)

Generated by `uv run python -m ml.run_baselines`. Mean absolute error (MAE) in
number of bikes or docks; lower is better.

- Train: pairs with target before {SPLIT.strftime(fmt)}
- Test: origins from {SPLIT.strftime(fmt)} to {TEST_END.strftime(fmt)}
- Data ends: {facts["data_end"].tz_convert(OSLO).strftime(fmt)}
- Pairs: {facts["train_pairs"]} train, {facts["test_pairs"]} test,
  {facts["test_stations"]} stations in test

## Bikes

{markdown_table(wide[wide["target"] == "bikes"].drop(columns="target"))}

## Docks (derived from predicted bikes)

{markdown_table(wide[wide["target"] == "docks"].drop(columns="target"))}

## Number of test pairs per subset

{markdown_table(counts.reset_index())}

## Data checks

- bikes + docks = capacity in {cap["share_equal"]:.1%} of active rows
  (below: {cap["share_below"]:.1%}, above: {cap["share_above"]:.1%});
  {cap["stations_always_equal"]} of {cap["stations"]} stations always equal,
  {cap["stations_constant_sum"]} have a constant sum.
- Bikes above capacity: {cap["share_bikes_above_capacity"]:.2%} of active rows.
- Pairs excluded from {excluded["total"]} in the test period (one pair can fail
  several rules): missing value {excluded["missing"]}, inactive
  {excluded["inactive"]}, frozen {excluded["frozen"]}, unknown capacity
  {excluded["no_capacity"]}.
- Frozen stations in the test period: {", ".join(facts["frozen_stations"]) or "none"}
- `same_time_last_week` fell back to `unchanged` for
  {facts["last_week_fallback"]:.1%} of test pairs.
"""


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    table, facts = run(load_status(), load_stations())
    RESULTS_DIR.mkdir(exist_ok=True)
    table.to_csv(RESULTS_DIR / "baselines.csv", index=False, float_format="%.4f")
    text = report(table, facts)
    (RESULTS_DIR / "baselines.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
